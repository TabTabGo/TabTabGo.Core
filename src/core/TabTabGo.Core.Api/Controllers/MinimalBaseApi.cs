/// <summary>
/// Options of the routes generated by <see cref="SetupEntityRouters.MapEntityRoutes{TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest}(IEndpointRouteBuilder, string, Action{EntityRouterOptions{TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest}}?)"/>.
/// </summary>
public class EntityRouterOptions<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>
    where TEntity : class, IEntity
    where TViewModel : class
    where TCreateRequest : class
{
    /// <summary>Scope criteria always applied to the search route.</summary>
    public Expression<Func<TEntity, bool>>? SearchFixCriteria { get; set; } = null;

    /// <summary>
    /// Scope criteria always applied when an entity is looked up by key: GET by id, and also PATCH and DELETE (an entity
    /// outside the scope answers 404 on every one of them).
    /// </summary>
    public Expression<Func<TEntity, bool>>? GetFixCriteria { get; set; } = null;

    /// <summary>Scope criteria always applied to the export route.</summary>
    public Expression<Func<TEntity, bool>>? ExportFixCriteria { get; set; } = null;

    /// <summary>Path segment put before the controller name, for example "api".</summary>
    public string? ControllerPrefix { get; set; } = null;

    /// <summary>Version segment put after the prefix, for example "v1".</summary>
    public string? Version { get; set; } = null;

    /// <summary>The route prefix: <c>ControllerPrefix/</c> and <c>Version/</c> when set, otherwise empty.</summary>
    public string GetRoutePrefix()
    {
        var routeBuilder = new StringBuilder();
        if (!string.IsNullOrEmpty(ControllerPrefix))
        {
            routeBuilder.Append(ControllerPrefix.Trim('/') + "/");
        }

        if (!string.IsNullOrEmpty(Version))
        {
            routeBuilder.Append(Version.Trim('/') + "/");
        }

        return routeBuilder.ToString();
    }
}

/// <summary>
/// Generates the CRUD minimal-API routes of an entity over <see cref="IBaseService{TEntity, TKey}"/>.
/// </summary>
public static class SetupEntityRouters
{
    /// <summary>
    /// Maps the entity routes: search (GET), get (GET id), export (POST export/format), create (POST), patch (PATCH id) and delete (DELETE id).
    /// Services are resolved per request, so scoped services (and their DbContext) are never shared between requests.
    /// </summary>
    /// <param name="app">The application</param>
    /// <param name="controllerName">Route name, for example "products"</param>
    /// <param name="setEntityRouteOptions">Optional route options</param>
    public static WebApplication MapEntityRoutes<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>(
        this WebApplication app,
        string controllerName,
        Action<EntityRouterOptions<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>>? setEntityRouteOptions =
            null)
        where TEntity : class, IEntity
        where TViewModel : class
        where TCreateRequest : class
        where TUpdateRequest : class
    {
        MapEntityRoutes<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>((IEndpointRouteBuilder)app, controllerName, setEntityRouteOptions);
        return app;
    }

    /// <summary>
    /// Maps the entity routes on any endpoint route builder (see the <see cref="WebApplication"/> overload).
    /// </summary>
    /// <param name="app">The route builder</param>
    /// <param name="controllerName">Route name, for example "products"</param>
    /// <param name="setEntityRouteOptions">Optional route options</param>
    /// <exception cref="InvalidOperationException">
    /// The name is empty, no <see cref="IBaseService{TEntity, TKey}"/> is registered, or there is no mapper and the create
    /// request is not an entity
    /// </exception>
    public static IEndpointRouteBuilder MapEntityRoutes<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>(
        this IEndpointRouteBuilder app,
        string controllerName,
        Action<EntityRouterOptions<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>>? setEntityRouteOptions =
            null)
        where TEntity : class, IEntity
        where TViewModel : class
        where TCreateRequest : class
        where TUpdateRequest : class
    {
        ArgumentNullException.ThrowIfNull(app);
        if (string.IsNullOrWhiteSpace(controllerName))
        {
            throw new InvalidOperationException("Controller name is required");
        }

        // fail fast on wiring mistakes; instances are resolved per request, never from the root provider
        var isService = app.ServiceProvider.GetService<IServiceProviderIsService>();
        if (isService != null && !isService.IsService(typeof(IBaseService<TEntity, TKey>)))
        {
            throw new InvalidOperationException($"No service found for {typeof(IBaseService<TEntity, TKey>).Name}<{typeof(TEntity).Name}>");
        }

        if (isService != null && !isService.IsService(typeof(IMapper<TEntity, TViewModel>)) &&
            !typeof(TEntity).IsAssignableFrom(typeof(TCreateRequest)))
        {
            throw new InvalidOperationException(
                $"No IMapper<{typeof(TEntity).Name}, {typeof(TViewModel).Name}> is registered and {typeof(TCreateRequest).Name} is not a {typeof(TEntity).Name}. " +
                "Register a mapper or use the entity as the create request.");
        }

        var options = new EntityRouterOptions<TEntity, TKey, TViewModel, TCreateRequest, TUpdateRequest>();
        setEntityRouteOptions?.Invoke(options);

        var entityName = typeof(TEntity).Name;
        var getScope = options.GetFixCriteria?.Compile();
        var root = "/" + options.GetRoutePrefix() + controllerName.Trim('/');
        var group = app.MapGroup(root).WithTags(entityName).RequireAuthorization();

        // Search
        group.MapGet("", async Task<Results<Ok<object>, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            ODataQueryOptions<TEntity> query,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            [FromServices] IMapper<TEntity, TViewModel>? mapper,
            CancellationToken cancellationToken) =>
        {
            logger.LogTrace("REST request to search {EntityName}", entityName);
            try
            {
                var entitiesResult = await service.GetPageList(query, options.SearchFixCriteria, cancellationToken: cancellationToken);
                return TypedResults.Ok<object>(mapper == null ? entitiesResult : mapper.MapPaging(entitiesResult));
            }
            catch (ApiException ex)
            {
                return Failure(ex, http);
            }
        });

        // Get by id
        group.MapGet("{id}", async Task<Results<Ok<object>, NotFound<ApiErrorBody>, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            TKey id,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            [FromServices] IMapper<TEntity, TViewModel>? mapper,
            DateTimeOffset? lastUpdatedDate = null,
            string? expand = null,
            CancellationToken cancellationToken = default) =>
        {
            logger.LogTrace("Getting {EntityName} with id {Id}", entityName, id);
            try
            {
                var entity = await service.GetByKey(id, lastUpdatedDate, expand?.Split(','),
                    fixCriteria: options.GetFixCriteria, cancellationToken: cancellationToken);
                if (entity == null)
                {
                    return TypedResults.NotFound(ApiErrorResponses.NotFound(entityName, null, http));
                }

                var entityViewModel = mapper?.MapToViewModel(entity);
                return TypedResults.Ok<object>(entityViewModel != null ? entityViewModel : entity);
            }
            catch (ApiException ex)
            {
                return Failure(ex, http);
            }
        });

        // Export
        group.MapPost("export/{format}", async Task<Results<FileStreamHttpResult, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            ExportType format,
            ODataQueryOptions<TEntity> query,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            [FromBody] ExportConfiguration? export = null,
            CancellationToken cancellationToken = default) =>
        {
            logger.LogTrace("REST request to export {EntityName} to type {ExportType}", entityName, format);
            export ??= new ExportConfiguration();
            if (string.IsNullOrEmpty(export.FileName))
            {
                // FileExtenstion already starts with the dot
                export.FileName = $"{entityName}_{DateTime.UtcNow:yyyyMMdd}{format.FileExtenstion()}";
            }

            try
            {
                export.FileType = format;
                var stream = await service.ExportFile<object>(export, query,
                    fixCriteria: options.ExportFixCriteria, cancellationToken: cancellationToken);
                return TypedResults.File(stream, "application/octet-stream", export.FileName);
            }
            catch (NotImplementedException)
            {
                return Json(HttpStatusCode.NotImplemented,
                    ApiErrorResponses.Failure($"{entityName} export is not implemented", $"{entityName}_Export_Not_Implemented".ToUpperInvariant(), http));
            }
            catch (ApiException ex)
            {
                return Failure(ex, http);
            }
        });

        // Create
        group.MapPost("", async Task<Results<Created<object>, BadRequest<ApiErrorBody>, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            TCreateRequest requestedEntity,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            [FromServices] IMapper<TEntity, TViewModel>? mapper,
            [FromServices] IValidationService<TEntity, TCreateRequest>? validateService,
            CancellationToken cancellationToken) =>
        {
            logger.LogTrace("Creating a new {EntityName}", entityName);

            var validationResult = validateService != null
                ? await validateService.Validate(requestedEntity, cancellationToken)
                : null;

            if (validationResult is { IsValid: false })
            {
                logger.LogInformation("Validation failed for {EntityName} with errors {@ValidationResult}", entityName, validationResult);
                return TypedResults.BadRequest(ApiErrorResponses.Validation(
                    $"Validation failed for create {controllerName}",
                    $"Create_Validation_Failed_{controllerName}".ToUpperInvariant(), validationResult, http));
            }

            try
            {
                var entity = mapper != null ? mapper.MapFromRequest(requestedEntity) : requestedEntity as TEntity;
                var createdEntity = await service.Create(entity, cancellationToken);
                var id = service.GetKey(createdEntity);
                logger.LogInformation("Created {EntityName} with id {Id}", entityName, id);
                var entityViewModel = mapper?.MapToViewModel(createdEntity);

                return TypedResults.Created($"{root}/{id}", entityViewModel != null ? (object)entityViewModel : createdEntity);
            }
            catch (ApiException ex)
            {
                logger.LogError(ex, "Failed to create {EntityName}", entityName);
                return Failure(ex, http);
            }
            catch (Exception e)
            {
                logger.LogError(e, "Failed to create {EntityName}", entityName);
                return Json(HttpStatusCode.InternalServerError,
                    ApiErrorResponses.Failure($"Failed to create {entityName}.", $"Create_{entityName}_Failed".ToUpperInvariant(), http));
            }
        });

        // Patch
        group.MapPatch("{id}", async Task<Results<Ok<object>, BadRequest<ApiErrorBody>, NotFound<ApiErrorBody>, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            TKey id,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            [FromServices] IMapper<TEntity, TViewModel>? mapper,
            [FromServices] IValidationService<TEntity, TCreateRequest>? validateService,
            CancellationToken cancellationToken) =>
        {
            logger.LogTrace("REST request to patch {EntityName}", entityName);

            if (id == null || EqualityComparer<TKey>.Default.Equals(id, default!)) // justified: a key of a generic type; default is the unset value the comparison wants
            {
                return TypedResults.BadRequest(ApiErrorResponses.Failure("Invalid Id", "Invalid_Id".ToUpperInvariant(), http));
            }

            // JsonPatchDocument<T> is a Newtonsoft type that System.Text.Json cannot bind, so the body is read here
            var changes = await ReadPatchDocumentAsync<TEntity>(http.Request, cancellationToken);
            if (changes == null)
            {
                return TypedResults.BadRequest(ApiErrorResponses.Failure("Invalid patch document", "INVALID_PATCH_DOCUMENT", http));
            }

            try
            {
                service.EnsurePatchable(changes);

                // looked up inside the scope: an entity outside the scope is a 404, as on GET
                var entity = await service.GetByKey(id, fixCriteria: options.GetFixCriteria, cancellationToken: cancellationToken);
                if (entity == null)
                {
                    return TypedResults.NotFound(ApiErrorResponses.NotFound(entityName, id, http));
                }

                changes.ApplyTo(entity, error =>
                {
                    if (error.Operation.OperationType != OperationType.Test &&
                        error.Operation.OperationType != OperationType.Invalid)
                    {
                        service.HandleJsonOperator(error.Operation, error.AffectedObject);
                    }
                });

                // the patch must not move the entity out of the scope it was found in; nothing is saved
                if (getScope != null && !getScope(entity))
                {
                    return TypedResults.NotFound(ApiErrorResponses.NotFound(entityName, id, http));
                }

                var validationResult = validateService != null
                    ? await validateService.Validate(entity, cancellationToken)
                    : null;
                if (validationResult is { IsValid: false })
                {
                    return TypedResults.BadRequest(ApiErrorResponses.Validation("Invalid patch request", "Invalid_Patch_Request".ToUpperInvariant(), validationResult, http));
                }

                // saved inside a transaction that the database scope check can veto (foreign keys and navigations count there)
                var updated = await service.UpdateChanges(id, entity, options.GetFixCriteria, cancellationToken);
                var entityViewModel = mapper?.MapToViewModel(updated);
                return TypedResults.Ok<object>(entityViewModel != null ? entityViewModel : updated);
            }
            catch (ApiException ex)
            {
                logger.LogError(ex, "Failed to update {EntityName}", entityName);
                return Failure(ex, http);
            }
            catch (Exception e)
            {
                logger.LogError(e, "Failed to update {EntityName}", entityName);
                return Json(HttpStatusCode.InternalServerError,
                    ApiErrorResponses.Failure($"Failed to update {entityName}.", "Update_Entity_Failed".ToUpperInvariant(), http));
            }
        });

        // Delete
        group.MapDelete("{id}", async Task<Results<Ok<object>, NotFound<ApiErrorBody>, JsonHttpResult<ApiErrorBody>>> (
            HttpContext http,
            TKey id,
            [FromServices] IBaseService<TEntity, TKey> service,
            [FromServices] ILogger<TEntity> logger,
            CancellationToken cancellationToken) =>
        {
            logger.LogDebug("REST request to delete {EntityName} : {Id}", entityName, id);

            try
            {
                // looked up inside the scope: an entity outside the scope is a 404, as on GET
                if (await service.GetByKey(id, fixCriteria: options.GetFixCriteria, cancellationToken: cancellationToken) == null)
                {
                    return TypedResults.NotFound(ApiErrorResponses.NotFound(entityName, id, http));
                }

                if (!await service.CanDelete(id, cancellationToken))
                {
                    return Json(HttpStatusCode.PreconditionFailed,
                        ApiErrorResponses.Failure($"{entityName} #{id} can't be deleted", $"{entityName}_Cannot_Delete".ToUpperInvariant(), http));
                }

                await service.Delete(id, cancellationToken);
                return TypedResults.Ok<object>(new
                {
                    Message = $"{entityName} deleted successfully",
                    Code = $"{entityName}_Deleted".ToUpperInvariant()
                });
            }
            catch (ApiException ex)
            {
                logger.LogError(ex, "Failed to delete {EntityName} with Id {Id}", entityName, id);
                return Failure(ex, http);
            }
            catch (Exception e)
            {
                logger.LogError(e, "Failed to delete {EntityName} with Id {Id}", entityName, id);
                return Json(HttpStatusCode.InternalServerError,
                    ApiErrorResponses.Failure($"Failed to delete {entityName}.", "Delete_Entity_Failed".ToUpperInvariant(), http));
            }
        });

        return app;
    }

    private static async Task<JsonPatchDocument<T>?> ReadPatchDocumentAsync<T>(HttpRequest request, CancellationToken cancellationToken) where T : class
    {
        try
        {
            using var reader = new StreamReader(request.Body, Encoding.UTF8, detectEncodingFromByteOrderMarks: true, leaveOpen: true);
            var text = await reader.ReadToEndAsync(cancellationToken);
            return Newtonsoft.Json.JsonConvert.DeserializeObject<JsonPatchDocument<T>>(text);
        }
        catch (Newtonsoft.Json.JsonException)
        {
            return null;
        }
    }

    private static JsonHttpResult<ApiErrorBody> Failure(ApiException exception, HttpContext http) =>
        Json(exception.HttpStatusCode, ApiErrorResponses.From(exception, http));

    private static JsonHttpResult<ApiErrorBody> Json(HttpStatusCode status, ApiErrorBody body) =>
        TypedResults.Json(body, SerializerEngine.JsonSerializationSettings, statusCode: (int)status);
}
